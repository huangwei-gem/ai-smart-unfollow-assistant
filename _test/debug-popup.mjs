import { setTimeout as sleep } from 'node:timers/promises';
const BASE = 'http://127.0.0.1:9222';
const targets = await (await fetch(BASE + '/json/list')).json();
const sw = targets.find(t => t.type === 'service_worker');
const extId = sw.url.match(/chrome-extension:\/\/([^/]+)/)[1];
console.log('extId:', extId);
const t = await (await fetch(BASE + '/json/new?' + encodeURIComponent('about:blank'), { method: 'PUT' })).json();
await sleep(500);
const ws = new WebSocket(t.webSocketDebuggerUrl);
await new Promise(r => ws.addEventListener('open', r));
let id = 0; const pend = new Map();
ws.addEventListener('message', ev => { const m = JSON.parse(ev.data); if (m.id && pend.has(m.id)) { pend.get(m.id)(m.result); pend.delete(m.id); } });
const send = (method, params={}) => new Promise(r => { pend.set(++id, r); ws.send(JSON.stringify({ id, method, params })); });
const ev = (expr) => send('Runtime.evaluate', { expression: expr, returnByValue: true, awaitPromise: true }).then(r => r.result?.value);
await send('Page.enable');
await send('Page.navigate', { url: `chrome-extension://${extId}/popup/popup.html` });
await sleep(2500);
console.log(JSON.stringify(await ev('({href: location.href, state: document.readyState, hasSave: !!document.getElementById("save"), bodyLen: document.body ? document.body.innerHTML.length : -1, scripts: [...document.scripts].map(s=>s.src)})'), null, 1));
process.exit(0);
